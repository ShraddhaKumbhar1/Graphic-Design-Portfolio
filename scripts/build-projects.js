#!/usr/bin/env node
/*
  Builds one static page per project: work/{id}.html
  Source of truth: assets/projects.js (the same data the home gallery uses).

  Run after editing a project:   node scripts/build-projects.js
  No dependencies. Pages for projects that no longer exist are removed.
*/
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const outDir = path.join(root, 'work');
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'assets', 'projects.js'), 'utf8'), ctx);
const S = ctx.window.STUDIO;
const P = ctx.window.PROJECTS;

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const pad = (n) => String(n).padStart(2, '0');
const ref = '?utm_source=zinos_portfolio&amp;utm_medium=referral';
const contrast = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return ((n >> 16) * 299 + ((n >> 8) & 255) * 587 + (n & 255) * 114) / 1000 > 150 ? '#0B0B0F' : '#FFFFFF';
};

function page(p, i) {
  const prev = P[(i - 1 + P.length) % P.length];
  const next = P[(i + 1) % P.length];
  const img = `../assets/work/${p.cover}`;
  const mail = `mailto:${S.email}?subject=${encodeURIComponent('New project')}`;
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(p.title)} · ${esc(p.discipline)} · ZINOS Design Studio</title>
  <meta name="description" content="${esc(p.summary)}">
  <meta property="og:type" content="article">
  <meta property="og:title" content="${esc(p.title)} · ZINOS Design Studio">
  <meta property="og:description" content="${esc(p.summary)}">
  <meta property="og:image" content="${img}-2400.jpg">
  <meta name="theme-color" content="#0B0B0F">
  <link rel="icon" href="../assets/logo/favicon.svg" type="image/svg+xml">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=DM+Sans:opsz,wght@9..40,200;9..40,300;9..40,400;9..40,500&family=Michroma&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="../styles.css">
  <script src="../assets/brand.js" defer></script>
  <script src="../assets/nav.js" defer></script>
  <script src="../assets/smooth-scroll.js" defer></script>
</head>
<!-- Generated by scripts/build-projects.js from assets/projects.js. Edit the data, then rebuild. -->
<body class="page-case">
  <a class="skip" href="#content">Skip to content</a>

  <header class="nav is-solid" data-nav>
    <a href="../index.html" class="nav__logo" data-logo="wordmark" aria-label="ZINOS, home"></a>
    <nav aria-label="Main">
      <ul class="nav__links">
        <li><a href="../index.html#work" aria-current="page">Work</a></li>
        <li><a href="../index.html#services">Services</a></li>
        <li><a href="../index.html#contact">Contact</a></li>
      </ul>
    </nav>
  </header>

  <main id="content" class="case">
    <div class="case__crumbs">
      <a href="../index.html#work">← All work</a>
      <span class="caption">${pad(i + 1)} / ${pad(P.length)} · ${esc(p.discipline)}</span>
    </div>

    <header class="case__head">
      <div>
        <span class="caption">${esc(p.client)} · ${p.year}</span>
        <h1 class="h1">${esc(p.title)}</h1>
      </div>
      <p class="lead">${esc(p.summary)}</p>
    </header>

    <figure class="case__cover" style="background:${p.ground}">
      <img src="${img}-1200.jpg" srcset="${img}-1200.jpg 1200w, ${img}-2400.jpg 2400w" sizes="calc(100vw - 80px)"
        alt="${esc(p.photo.alt)}" width="2400" height="1600" fetchpriority="high" decoding="async">
      <figcaption class="caption">Photo: <a href="${p.photo.url}${ref}" rel="noopener">${esc(p.photo.by)}</a> on <a href="https://unsplash.com/${ref}" rel="noopener">Unsplash</a></figcaption>
    </figure>

    <dl class="case__facts">
      <div><dt>Role</dt><dd>${esc(p.role)}</dd></div>
      <div><dt>Client</dt><dd>${esc(p.client)}</dd></div>
      <div><dt>Discipline</dt><dd>${esc(p.discipline)}</dd></div>
      <div><dt>Year</dt><dd>${p.year}</dd></div>
    </dl>

    <section class="case__brief" aria-labelledby="brief-title">
      <h2 class="h2" id="brief-title">The brief</h2>
      <div>
        <p>${esc(p.brief)}</p>
        <h3>Delivered</h3>
        <ul class="case__deliv">
${p.deliverables.map((d) => `          <li>${esc(d)}</li>`).join('\n')}
        </ul>
      </div>
    </section>

    <section class="case__why" aria-labelledby="why-title">
      <h2 class="h2" id="why-title">Why it works</h2>
      <div>
        <blockquote>${esc(p.decision)}</blockquote>
        <div class="case__palette" aria-label="Colour palette">
${p.palette.map((c) => `          <div style="background:${c.hex};color:${contrast(c.hex)}">${esc(c.name)}<br>${c.hex}</div>`).join('\n')}
        </div>
        <p class="case__type">${esc(p.type)}</p>
      </div>
    </section>

    <nav class="case__pager" aria-label="More projects">
      <a class="prev" href="${prev.id}.html"><span>Previous project</span><b>← ${esc(prev.title)}</b></a>
      <a class="next" href="${next.id}.html"><span>Next project</span><b>${esc(next.title)} →</b></a>
    </nav>
  </main>

  <section class="contact" aria-labelledby="contact-title">
    <h2 id="contact-title" class="display">Now booking projects.</h2>
    <div class="contact__row">
      <p class="lead">Tell us what you need and when. You get a reply the same day, and a fixed price within two days.</p>
      <a class="button" href="${mail}">Start a project</a>
    </div>
  </section>

  <footer class="footer">
    <span class="footer__mark" data-logo="monogram" aria-label="ZINOS"></span>
    <a class="caption" href="${mail}">${esc(S.email)}</a>
    <p class="caption footer__credit">Cover photo by <a href="${p.photo.url}${ref}" rel="noopener">${esc(p.photo.by)}</a> on <a href="https://unsplash.com/${ref}" rel="noopener">Unsplash</a>.</p>
    <p class="caption">© 2026 ZINOS Design Studio</p>
  </footer>
</body>
</html>
`;
}

fs.mkdirSync(outDir, { recursive: true });
const keep = new Set(P.map((p) => `${p.id}.html`));
for (const f of fs.readdirSync(outDir)) {
  if (f.endsWith('.html') && !keep.has(f)) { fs.unlinkSync(path.join(outDir, f)); console.log('removed  work/' + f); }
}
P.forEach((p, i) => {
  fs.writeFileSync(path.join(outDir, `${p.id}.html`), page(p, i));
  console.log('wrote    work/' + p.id + '.html');
});
